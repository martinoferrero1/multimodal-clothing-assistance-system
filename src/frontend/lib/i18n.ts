const messages: Record<Language, Record<MessageKey, string>> = {
  en: enMessages,
  es: esMessages,
};

export function isLanguage(value: unknown): value is Language {
  return typeof value === "string" && supportedLanguages.includes(value as Language);
}

export function translate(language: Language, key: MessageKey, params?: TranslationParams): string {
  const message = messages[language][key];
  if (!params) {
    return message;
  }
  return message.replace(/\{(\w+)\}/g, (match, name: string) =>
    params[name] === undefined ? match : String(params[name]),
  );
}

export function pluralKey(
  language: Language,
  count: number,
  singular: MessageKey,
  plural: MessageKey,
): MessageKey {
  return new Intl.PluralRules(language).select(count) === "one" ? singular : plural;
}

export function languageLocale(language: Language): string {
  return language === "es" ? "es-ES" : "en-US";
}
